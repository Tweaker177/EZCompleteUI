-- Ricochet Blast leaderboard. Kept separate from br_highscores (the maze game).
create table if not exists public.br_ricochet_highscores (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 20),
  score integer not null check (score between 0 and 999999),
  created_at timestamptz not null default now()
);

create index if not exists br_ricochet_highscores_score_idx
  on public.br_ricochet_highscores (score desc, created_at asc);

alter table public.br_ricochet_highscores enable row level security;
